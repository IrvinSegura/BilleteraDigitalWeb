import { execFileSync } from 'node:child_process'

// The API's database, as `docker compose up -d` in the backend repo starts it. Point these elsewhere when the tests
// run against a copy of the API with its own database.
const CONTAINER = process.env.E2E_DB_CONTAINER ?? 'billeterra-digital-postgres-1'
const DATABASE = process.env.E2E_DB_NAME ?? 'wallet'
const OWNER = process.env.E2E_DB_USER ?? 'wallet_owner'

function psql(sql: string): string {
  return execFileSync('docker', ['exec', CONTAINER, 'psql', '-U', OWNER, '-d', DATABASE, '-tAc', sql], { encoding: 'utf8' })
}

function setRole(email: string, role: string) {
  // Test emails are generated by newUserDetails: letters, digits, dashes, dots and @ only, nothing to escape
  if (!/^[\w.@-]+$/.test(email)) {
    throw new Error(`Unexpected test email: ${email}`)
  }
  const output = psql(`UPDATE users SET role = '${role}' WHERE email = '${email}'`)
  if (!output.includes('UPDATE 1')) {
    throw new Error(`Could not make ${email} ${role}: ${output}`)
  }
}

/** Makes a test user a support agent; quicker than the admin console. They must sign in afterwards for it to count. */
export function promoteToSupport(email: string) {
  setRole(email, 'SUPPORT')
}

/**
 * Makes a test user an administrator. The API has no endpoint for it (it only creates the one administrator in its
 * configuration, at startup), so the role is set in the database. The user must sign in again for it to count.
 */
export function promoteToAdmin(email: string) {
  setRole(email, 'ADMIN')
}

/**
 * Turns the agents earlier runs left behind back into customers. Agents take any queued case, so on a database that
 * outlives a run (a developer's) the next run's case could go to one of them instead of the new agent. Only test
 * accounts are touched; on CI the database starts empty and this changes nothing.
 */
export function demoteLeftoverAgents() {
  psql(`UPDATE users SET role = 'USER' WHERE role = 'SUPPORT' AND email LIKE 'e2e-%@wallet.local'`)
  // A case an earlier run gave back to the queue would come to this run's agent before the one it expects
  psql(`UPDATE support_conversations c SET status = 'RESOLVED', resolution = 'OTHER', resolved_at = now()
        FROM users u WHERE u.id = c.user_id AND c.status = 'QUEUED' AND u.email LIKE 'e2e-%@wallet.local'`)
}
